#!/usr/bin/env python3
"""Кальки з російської: механічний пошук у тексті книги.

Навіщо. Книга українська, написана за двоє діб і **без людського
коректора** — про це сказано в її ж анотації. Кальки з російської — саме
той рід помилок, який коректор ловить першим, а автор у поспіху не
бачить узагалі: слово виглядає звичним, бо звичне воно з іншої мови.

Загальний правопис їх теж не ловить: `спiвпадати`, `на протязі`,
`в якості` — усе це для орфографічного словника правильні українські
слова. Хибне тут не написання, а **вибір слова**.

Тому окремий перелік із заміною на кожен випадок. Перелік свідомо
короткий: сюди входить лише те, де заміна однозначна. Спірне (`являється`
проти `є`, `знаходитися` в значенні «бути розташованим`) не входить, бо
на спірному перевірка починає брехати, а інструмент, який бреше, за
тиждень перестають читати.

    factcheck/tools/calques.py        перевірити текст книги
    factcheck/tools/calques.py -v     показати рядок цілком
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from repo import ROOT  # noqa: E402  (root is found, not counted)
GRUPY = ("manual", "kartky", "dodatky", "inserts")

# (взірець, чим замінити, чому)
KALKY: list[tuple[str, str, str]] = [
    (r"\bна протязі\b", "протягом",
     "«на протязі» — це на сквозняку"),
    (r"\bв залежності від\b", "залежно від", ""),
    (r"\bв якості\b", "як", "«в якості прикладу» → «як приклад»"),
    (r"\bпо замовчуванн", "за замовчуванн", ""),
    (r"\bпо крайній мірі\b", "принаймні", ""),
    (r"\bяк мінімум\b", "щонайменше", ""),
    (r"\bна рахунок\b", "щодо", "«на рахунок» — це про банк"),
    (r"\bслідуюч", "наступн", ""),
    (r"\bспівпада", "збіга", ""),
    (r"\bприймати участь\b", "брати участь", ""),
    (r"\bне дивлячись на\b", "незважаючи на", ""),
    (r"\bв кінці кінців\b", "зрештою", ""),
    (r"\bміроприємств", "захід", ""),
    (r"\bполучи(ти|в|ла|ло)\b", "отрима\\1", ""),
    (r"\bвідмінити\b", "скасувати", ""),
    (r"\bдіюч(ий|а|е|і)\b", "чинн\\1", "про норму, стандарт, правило"),
    (r"\bбільш детально\b", "докладніше", ""),
    (r"\bу випадку якщо\b", "якщо", ""),
    (r"\bприводить до\b", "призводить до", "про наслідок"),
    (r"\bвірн(ий|е|а|о)\b", "правильн\\1",
     "«вірний» — про відданість, не про правильність"),
    (r"\bлюб(ий|а|е|і)\b(?!\s*(?:до|дружин))", "будь-як\\1",
     "«любий» — це коханий"),
    (r"\bоб'єм пам", "обсяг пам", "пам'ять має обсяг, а не об'єм"),
    (r"\bвиключенн(я|ям|ями)\b(?![^\n]{0,40}(?:C\+\+|try|catch|throw))",
     "виняток", "`exception` у коді — окремий випадок, там лишається"),
]

# Що не перевіряємо: цитати чужого тексту, службові реєстри, листування.
PROPUSK_KATALOHY = ("factcheck", "zvyazok", "reviews", "docs", "build")
RE_KOD = re.compile(r"```.*?```|`[^`]+`", re.S)


def bez_kodu(t: str) -> str:
    """Замінити код пробілами, зберігши позиції рядків.

    Саме зберігши: інакше номер рядка в звіті поїде, і знахідку
    доведеться шукати очима — тобто інструмент з'їсть більше часу, ніж
    зекономить.
    """
    return RE_KOD.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), t)


def main() -> int:
    detalno = "-v" in sys.argv
    znaydeno = 0
    fayliv = 0
    for grupa in GRUPY:
        katalog = ROOT / grupa
        if not katalog.exists():
            continue
        for f in sorted(katalog.glob("*.md")):
            fayliv += 1
            tekst = bez_kodu(f.read_text(encoding="utf-8"))
            ryadky = tekst.split("\n")
            for vzirets, zamina, chomu in KALKY:
                for i, r in enumerate(ryadky, 1):
                    for m in re.finditer(vzirets, r, re.I):
                        znaydeno += 1
                        pryklad = re.sub(vzirets, zamina, m.group(0),
                                         flags=re.I)
                        print(f"   ✗ {f.relative_to(ROOT)}:{i}: "
                              f"«{m.group(0)}» → «{pryklad}»"
                              + (f"  ({chomu})" if chomu else ""))
                        if detalno:
                            print(f"        {r.strip()[:110]}")
    print(f"calques: файлів {fayliv}, взірців {len(KALKY)}, "
          f"знахідок {znaydeno}")
    return 1 if znaydeno else 0


if __name__ == "__main__":
    sys.exit(main())
