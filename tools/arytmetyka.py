def main() -> int:
    zbih = rozbizh = 0
    poperedniy = None
    for rozdil, nazva, vyraz, u_knyzi, dopusk in PEREVIRKY:
        if rozdil != poperedniy:
            print(f"\n── розділ {rozdil}")
            poperedniy = rozdil
        mayemo = vyraz()
        vidhyl = abs(mayemo - u_knyzi) / max(abs(u_knyzi), 1e-12)
        if vidhyl <= dopusk:
            zbih += 1
            print(f"   ✓ {nazva:<46} {u_knyzi:g}")
        else:
            rozbizh += 1
            print(f"   ✗ {nazva:<46} у книзі {u_knyzi:g}, "
                  f"рахунок {mayemo:.6g}  (відхилення {vidhyl:.1%})")
    print(f"\nперевірок: {zbih + rozbizh}; збіглося: {zbih}; "
          f"розбіжностей: {rozbizh}")
    return 1 if rozbizh else 0


if __name__ == "__main__":
    sys.exit(main())
